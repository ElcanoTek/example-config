"""Shared email bodies for the sender tests.

send_email refuses HTML outside the branded frame (EB001), so a test that is
about something else (attachments, recipients, the send-once ledger) sends
its body inside the smallest frame the rule accepts.
"""

from __future__ import annotations

from collections.abc import Mapping
from email import policy
from email.message import EmailMessage
from email.parser import BytesParser
from typing import Any


def framed(body: str) -> str:
    """`body` inside the canonical_template frame: container, header, footer."""
    return (
        '<html><body><table class="email-container" role="presentation" width="100%">'
        '<tr><td class="header-pad">Northwind</td></tr>'
        f"<tr><td>{body}</td></tr>"
        '<tr><td class="footer-pad">Generated by Victoria</td></tr>'
        "</table></body></html>"
    )


def sent_message(request: Mapping[str, Any]) -> EmailMessage:
    """The MIME message a captured SES request sends (send_email sends Raw)."""
    return BytesParser(policy=policy.default).parsebytes(request["Content"]["Raw"]["Data"])


def sent_body(request: Mapping[str, Any]) -> tuple[str, str]:
    """``(content_type, text)`` of a captured request's body part."""
    body = sent_message(request).get_body(preferencelist=("html", "plain"))
    assert body is not None
    return body.get_content_type(), body.get_content().replace("\r\n", "\n")


def sent_attachments(request: Mapping[str, Any]) -> list[dict[str, Any]]:
    """Every attachment and inline part of a captured request, in MIME order.

    Inline parts come first (they sit beside the HTML in multipart/related),
    then regular attachments.
    """
    parts: list[dict[str, Any]] = []
    for part in sent_message(request).walk():
        disposition = part.get_content_disposition()
        if part.is_multipart() or disposition not in {"attachment", "inline"}:
            continue
        parts.append(
            {
                "FileName": part.get_filename(),
                "RawContent": part.get_payload(decode=True),
                "ContentType": part.get_content_type(),
                "ContentDisposition": disposition.upper(),
                "ContentId": str(part.get("Content-ID", "")).strip("<>"),
            }
        )
    return parts
