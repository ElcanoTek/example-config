"""Shared email bodies for the sender tests.

send_email refuses HTML outside the branded frame (EB001), so a test that is
about something else (attachments, recipients, the send-once ledger) sends
its body inside the smallest frame the rule accepts.
"""

from __future__ import annotations


def framed(body: str) -> str:
    """`body` inside the canonical_template frame: container, header, footer."""
    return (
        '<html><body><table class="email-container" role="presentation" width="100%">'
        '<tr><td class="header-pad">Northwind</td></tr>'
        f"<tr><td>{body}</td></tr>"
        '<tr><td class="footer-pad">Generated by Victoria</td></tr>'
        "</table></body></html>"
    )
